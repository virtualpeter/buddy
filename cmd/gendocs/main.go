// Command gendocs writes audience-specific docs and help fragments from docspec topics.
//
//	go run ./cmd/gendocs
//	make gendocs
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode"

	// Register feature topics.
	_ "buddy/internal/buddy"
	"buddy/internal/docspec"
)

func main() {
	root, err := findRepoRoot()
	if err != nil {
		fatal(err)
	}
	topics := docspec.All()
	if len(topics) == 0 {
		fatal(fmt.Errorf("no docspec topics registered"))
	}
	humanDir := filepath.Join(root, "docs", "generated", "human")
	agentDir := filepath.Join(root, "docs", "generated", "agent")
	helpDir := filepath.Join(root, "internal", "help")
	if err := os.MkdirAll(humanDir, 0o755); err != nil {
		fatal(err)
	}
	if err := os.MkdirAll(agentDir, 0o755); err != nil {
		fatal(err)
	}

	for _, t := range topics {
		base := topicBase(t.ID)
		banner := generatedBannerMD(t.ID)
		humanPath := filepath.Join(humanDir, base+".md")
		agentPath := filepath.Join(agentDir, base+".md")
		if err := writeFile(humanPath, banner+"\n"+docspec.RenderHuman(t)); err != nil {
			fatal(err)
		}
		if err := writeFile(agentPath, banner+"\n"+docspec.RenderAgent(t)); err != nil {
			fatal(err)
		}
		fmt.Printf("wrote %s\n", rel(root, humanPath))
		fmt.Printf("wrote %s\n", rel(root, agentPath))

		export := t.HelpExport
		if export == "" {
			continue
		}
		builtins := docspec.RenderBuiltinsHelpFragment(t)
		cli := ""
		if t.CLIHelp != "" {
			cli = docspec.RenderCLIHelp(t)
		}
		if builtins == "" && cli == "" {
			fatal(fmt.Errorf("%s: HelpExport=%q but BuiltinsHelp/CLIHelp empty", t.ID, export))
		}
		helpPath := filepath.Join(helpDir, export+"_gen.go")
		if err := writeFile(helpPath, renderHelpGo(t.ID, export, builtins, cli)); err != nil {
			fatal(err)
		}
		fmt.Printf("wrote %s\n", rel(root, helpPath))
	}
}

func topicBase(id string) string {
	base := strings.TrimPrefix(id, "docs/")
	if base == "" || base == id {
		return id
	}
	return base
}

func generatedBannerMD(topicID string) string {
	return fmt.Sprintf("<!-- Code generated by go run ./cmd/gendocs; DO NOT EDIT. Topic: %s -->", topicID)
}

func exportPascal(export string) string {
	parts := strings.FieldsFunc(export, func(r rune) bool {
		return r == '_' || r == '-'
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

func renderHelpGo(topicID, export, builtins, cli string) string {
	pas := exportPascal(export)
	var b strings.Builder
	b.WriteString("// Code generated by go run ./cmd/gendocs; DO NOT EDIT.\n")
	b.WriteString("// Topic: ")
	b.WriteString(topicID)
	b.WriteString(" (make gendocs).\n\n")
	b.WriteString("package help\n\n")
	if builtins != "" {
		b.WriteString("// ")
		b.WriteString(pas)
		b.WriteString("BuiltinsSection is spliced into Builtins.\n")
		b.WriteString("const ")
		b.WriteString(pas)
		b.WriteString("BuiltinsSection = ")
		b.WriteString(goRawString(builtins))
		b.WriteString("\n\n")
	}
	if cli != "" {
		b.WriteString("// ")
		b.WriteString(pas)
		b.WriteString("CLIHelp is the text for buddy help / CLI.\n")
		b.WriteString("const ")
		b.WriteString(pas)
		b.WriteString("CLIHelp = ")
		b.WriteString(goRawString(cli))
		b.WriteString("\n")
	}
	return b.String()
}

func goRawString(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconvQuote(s)
}

func strconvQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func writeFile(path, body string) error {
	if !strings.HasSuffix(body, "\n") {
		body += "\n"
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

func findRepoRoot() (string, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	dir := cwd
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from %s", cwd)
		}
		dir = parent
	}
}

func rel(root, path string) string {
	r, err := filepath.Rel(root, path)
	if err != nil {
		return path
	}
	return r
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "gendocs: %v\n", err)
	os.Exit(1)
}
