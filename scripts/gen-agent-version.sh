#!/usr/bin/env bash
# Write Agent version files. Display / wire version is the exact git tag when
# HEAD is clean and tagged; otherwise the short commit plus `-dirty`.
# CFBundleShortVersionString stays the last tag's semver so `make package` can
# match Buddy.app and the helper.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"

short="$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo dev)"
dirty=
if ! git -C "$root" diff --quiet 2>/dev/null || ! git -C "$root" diff --cached --quiet 2>/dev/null; then
	dirty=-dirty
fi
tag="$(git -C "$root" describe --tags --exact-match 2>/dev/null || true)"
if [[ -n "$tag" && -z "$dirty" ]]; then
	revision="$tag"
else
	revision="${short}${dirty}"
fi
tag_describe="$(git -C "$root" describe --tags --always --dirty 2>/dev/null || echo dev)"
marketing="$(printf '%s' "$tag_describe" | sed -E 's/^v//;s/-.*//')"
test -n "$marketing" || marketing=0.0.0
year="$(date +%Y)"
built_at="$(date '+%Y-%m-%d %H:%M')"
bundle_version="$(date -u +%Y%m%d.%H%M)"

swift="$root/macos/BuddyAgent/Sources/BuddyAgent/AgentVersion.generated.swift"
xcconfig="$root/macos/BuddyAgent/Version.xcconfig"

mkdir -p "$(dirname "$swift")"
cat >"$swift" <<SWIFT
// Code generated by scripts/gen-agent-version.sh; DO NOT EDIT.

enum AgentBuildVersion {
	/// Exact git tag when HEAD is clean and tagged; otherwise short commit (\`-dirty\` if needed).
	static let revision = "$revision"
	/// Period-delimited semver for CFBundleShortVersionString / pkgbuild.
	static let marketing = "$marketing"
	/// Local clock at generate time (About parenthetical).
	static let builtAt = "$built_at"
	/// Calendar year at generate time (\`NSHumanReadableCopyright\`).
	static let copyrightYear = "$year"
}
SWIFT

cat >"$xcconfig" <<XCC
// Code generated by scripts/gen-agent-version.sh; DO NOT EDIT.
MARKETING_VERSION = $marketing
CURRENT_PROJECT_VERSION = $bundle_version
COPYRIGHT_YEAR = $year
XCC

echo "gen-agent-version: revision=$revision marketing=$marketing built_at=$built_at year=$year"
